import { expect, test } from '@playwright/test'
import { authFile, openVehicle } from './fixtures'

test.use({ storageState: authFile('adnan') })

test('odometer: a decrease is explained, a reading is saved, then corrected with a reason', async ({ page }) => {
  await openVehicle(page, 'A84-O-352', 'Konum ve geçmiş')
  await page.getByRole('button', { name: 'Kilometre gir' }).click()
  const form = page.getByRole('dialog', { name: 'Kilometre gir' })
  await form.locator('#km').fill('68000')
  await expect(form.getByRole('alert')).toContainText('Kilometre geriye gidemez')
  await form.locator('#km').fill('99000')
  await expect(form.getByText('Doğruysa gerekçe girerek onaylayın')).toBeVisible()
  await form.getByRole('button', { name: 'Kaydet' }).click()
  await expect(form.locator('#largeJumpReason-error')).toBeVisible()
  await form.locator('#km').fill('69000')
  await form.getByRole('button', { name: 'Kaydet' }).click()
  await expect(form).toHaveCount(0)
  await expect(page.getByText('Kilometre kaydedildi: 69.000 km.')).toBeVisible()
  await expect(page.locator('section', { hasText: 'Kilometre gir' }).getByText('69.000 km')).toBeVisible()

  await page.getByRole('button', { name: 'Kilometre kaydı işlemleri' }).first().click()
  await page.getByRole('menuitem', { name: 'Düzelt' }).click()
  const fix = page.getByRole('dialog', { name: 'Kilometre kaydını düzelt' })
  await fix.locator('#fixKm').fill('68900')
  await fix.locator('#reason').fill('E2E: gösterge yanlış okundu')
  await fix.getByRole('button', { name: 'Düzeltmeyi kaydet' }).click()
  await expect(fix).toHaveCount(0)
  await expect(page.locator('section', { hasText: 'Kilometre gir' }).getByText('68.900 km')).toBeVisible()
  await expect(page.getByText('Düzeltildi:').first()).toBeVisible()
  await expect(page.getByText('E2E: gösterge yanlış okundu').first()).toBeVisible()
})

test('location: service then back to a branch; the home branch never changes', async ({ page }) => {
  await openVehicle(page, 'M62-A-238', 'Konum ve geçmiş')
  await page.getByRole('button', { name: 'Konumu güncelle' }).click()
  let form = page.getByRole('dialog', { name: 'Konumu güncelle' })
  await expect(form.getByText('Bu bir konum kaydıdır, transfer değildir.')).toBeVisible()
  await form.getByRole('radio', { name: /Serviste/ }).check()
  await form.locator('#description').fill('E2E Servis')
  await form.locator('#reason').fill('E2E: servise bırakıldı')
  const t = new Date(Date.now() - 2 * 3_600_000)
  await form.locator('#occurredAt').fill(
    new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Sarajevo', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }).format(t).replace(' ', 'T'),
  )
  await form.getByRole('button', { name: 'Kaydet' }).click()
  await expect(form).toHaveCount(0)
  const panel = page.locator('section', { hasText: 'Konumu güncelle' })
  await expect(panel.getByText('Serviste · E2E Servis')).toBeVisible()
  await expect(panel.getByText('Ana şube dışında')).toBeVisible()
  await page.getByRole('button', { name: 'Konumu güncelle' }).click()
  form = page.getByRole('dialog', { name: 'Konumu güncelle' })
  const sjj = await form.locator('#branchId option', { hasText: 'Sarajevo Aerodrom' }).getAttribute('value')
  await form.locator('#branchId').selectOption(sjj!)
  await form.locator('#reason').fill('E2E: servisten döndü')
  await form.getByRole('button', { name: 'Kaydet' }).click()
  await expect(form).toHaveCount(0)
  await expect(panel.getByText('Sarajevo Aerodrom').first()).toBeVisible()
  await expect(panel.getByText('Ana şube dışında')).toHaveCount(0)
  await expect(page.getByText('Serviste · E2E Servis → Sarajevo Aerodrom').or(page.getByText(/Serviste · E2E Servis\s*→\s*Sarajevo Aerodrom/)).first()).toBeVisible()
})
