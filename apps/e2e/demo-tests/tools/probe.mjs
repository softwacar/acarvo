import { createRequire } from 'node:module'
const require = createRequire(new URL('../../package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const b = await chromium.launch({ channel: 'msedge' }).catch(() => chromium.launch())
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, locale: 'tr-TR' })).newPage()
await p.goto('http://localhost:5174/kiralamalar/rn37')
await p.waitForLoadState('networkidle')
console.log('TR sample:', (await p.locator('main').innerText()).slice(0, 160).replace(/\n/g, ' | '))
await p.getByRole('button', { name: 'Demo', exact: true }).click()
await p.getByRole('menuitem', { name: /Dil:/ }).click()
await p.waitForTimeout(300)
console.log('EN sample:', (await p.locator('main').innerText()).slice(0, 240).replace(/\n/g, ' | '))
await p.goto('http://localhost:5174/takvim')
await p.waitForLoadState('networkidle')
console.log('lang after nav:', await p.evaluate(() => document.documentElement.lang), (await p.locator('main').innerText()).slice(0, 100).replace(/\n/g, ' | '))
await b.close()
