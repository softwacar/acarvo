# ACARVO local database setup.
# Creates the database roles (acarvo_owner, acarvo_app), the databases (acarvo, acarvo_test),
# writes .env with randomly generated role passwords, applies migrations and loads development data.
#
# Run it yourself in PowerShell from the repository root:
#   powershell -ExecutionPolicy Bypass -File scripts\setup-db.ps1
#
# Passwords are typed into hidden prompts or generated here. They are written only to the local
# .env file (ignored by Git) and are never printed.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root '.env'
$pgBin = 'C:\Program Files\PostgreSQL\17\bin'
$psql = Join-Path $pgBin 'psql.exe'

if (-not (Test-Path $psql)) { throw "psql bulunamadı: $psql. PostgreSQL 17 kurulu mu?" }
if (Test-Path $envFile) {
  $answer = Read-Host '.env zaten var. Veritabanı rolleri ve parolaları yeniden oluşturulsun mu? (evet/hayir)'
  if ($answer -ne 'evet') { Write-Host 'İptal edildi.'; exit 0 }
}

function New-Secret([int]$bytes = 32) {
  $buf = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buf)
  # URL-safe, no characters that need escaping in a connection string
  return ([Convert]::ToBase64String($buf) -replace '[+/=]', '').Substring(0, [Math]::Min(40, [int]($bytes * 1.3)))
}

function Read-Secret([string]$prompt) {
  $s = Read-Host $prompt -AsSecureString
  $b = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($s)
  try { return [Runtime.InteropServices.Marshal]::PtrToStringBSTR($b) } finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($b) }
}

$superPass = Read-Secret 'PostgreSQL "postgres" kullanıcısının parolası (kurulumda belirlediğiniz)'
$ownerPass = New-Secret
$appPass = New-Secret
$cookieSecret = New-Secret 48

$env:PGPASSWORD = $superPass
try {
  $sql = @"
\set ON_ERROR_STOP on
\set owner_pass '$ownerPass'
\set app_pass '$appPass'
DO `$`$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'acarvo_owner') THEN CREATE ROLE acarvo_owner LOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'acarvo_app') THEN CREATE ROLE acarvo_app LOGIN; END IF;
END `$`$;
ALTER ROLE acarvo_owner WITH LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE PASSWORD :'owner_pass';
ALTER ROLE acarvo_app WITH LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD :'app_pass';
SELECT 'CREATE DATABASE acarvo OWNER acarvo_owner' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'acarvo')\gexec
SELECT 'CREATE DATABASE acarvo_test OWNER acarvo_owner' WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'acarvo_test')\gexec
"@
  # SQL goes through stdin, so passwords never appear on a command line.
  $sql | & $psql -h localhost -U postgres -d postgres -q -X | Out-Null
  if ($LASTEXITCODE -ne 0) { throw 'Roller veya veritabanları oluşturulamadı.' }

  foreach ($db in 'acarvo', 'acarvo_test') {
    "\set ON_ERROR_STOP on`nREVOKE ALL ON DATABASE $db FROM PUBLIC;`nGRANT CONNECT ON DATABASE $db TO acarvo_app, acarvo_owner;`nREVOKE CREATE ON SCHEMA public FROM PUBLIC;" |
      & $psql -h localhost -U postgres -d $db -q -X | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "$db yetkileri ayarlanamadı." }
  }
} finally {
  Remove-Item Env:\PGPASSWORD -ErrorAction SilentlyContinue
  $superPass = $null
}

@"
# Local development configuration. Generated by scripts/setup-db.ps1. Never commit this file.
NODE_ENV=development
API_PORT=3001
WEB_ORIGIN=http://localhost:5173
DATABASE_URL=postgres://acarvo_app:$appPass@localhost:5432/acarvo
DATABASE_OWNER_URL=postgres://acarvo_owner:$ownerPass@localhost:5432/acarvo
TEST_DATABASE_URL=postgres://acarvo_app:$appPass@localhost:5432/acarvo_test
TEST_DATABASE_OWNER_URL=postgres://acarvo_owner:$ownerPass@localhost:5432/acarvo_test
COOKIE_SECRET=$cookieSecret
"@ | Set-Content -Path $envFile -Encoding utf8 -NoNewline
$ownerPass = $null; $appPass = $null; $cookieSecret = $null
Write-Host '.env oluşturuldu (parolalar gösterilmedi).'

Push-Location $root
try {
  npm run db:migrate --silent
  npm run db:migrate:test --silent
  Write-Host ''
  Write-Host 'Geliştirme verisi yükleniyor. Örnek kullanıcılar için bir giriş parolası belirleyin (en az 12 karakter).'
  $seedPass = Read-Secret 'Örnek kullanıcı parolası'
  if ($seedPass.Length -lt 12) { throw 'Parola en az 12 karakter olmalı.' }
  $env:SEED_PASSWORD = $seedPass
  npm run db:seed --silent
} finally {
  Remove-Item Env:\SEED_PASSWORD -ErrorAction SilentlyContinue
  $seedPass = $null
  Pop-Location
}
Write-Host ''
Write-Host 'Kurulum tamamlandı. Uygulamayı başlatmak için: npm run dev'
